#!/usr/bin/env python3
"""Generate plan/issues.json and the ticket section of docs/plan.md from plan/tickets.yaml.

issues.json is a list of {title, body, labels, milestone} objects, ready for e.g.
  jq -c '.[]' plan/issues.json | while read i; do gh issue create --title "$(jq -r .title <<<"$i")" \
     --body "$(jq -r .body <<<"$i")" --label "$(jq -r '.labels|join(",")' <<<"$i")" \
     --milestone "$(jq -r .milestone <<<"$i")"; done
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- TICKETS:START (generated by scripts/gen_issues.py) -->", "<!-- TICKETS:END -->"


def _load():
    return yaml.safe_load((ROOT / "plan" / "tickets.yaml").read_text())


def build_issues() -> list[dict]:
    data = _load()
    roles, ms = data["roles"], data["milestones"]
    out = []
    for t in data["tickets"]:
        deps = ", ".join(t["depends_on"]) or "none"
        body = "\n".join([
            f"**Ticket:** {t['id']}  ",
            f"**Owner role:** {roles[t['owner']]}  ",
            f"**Milestone:** {ms[t['milestone']]['title']} (due {ms[t['milestone']]['due']})  ",
            f"**Depends on:** {deps}  ",
            f"**Implements contract:** `{t['contract']}`",
            "",
            "### Acceptance criteria",
            *[f"- [ ] {a}" for a in t["acceptance"]],
            "",
            "### Definition of done",
            "- [ ] Acceptance criteria met and demoed to the Architect",
            "- [ ] `scripts/validate_contracts.py` and all CI jobs green",
            "- [ ] Contract unchanged, or contract change merged first via an ADR/PR approved by the Architect",
        ])
        out.append({
            "title": f"[{t['id']}] {t['title']}",
            "body": body,
            "labels": [f"role:{t['owner']}", f"milestone:{t['milestone']}", "type:feature"]
                      + (["contract-impl"] if t["contract"].startswith("contracts/") else []),
            "milestone": ms[t["milestone"]]["title"],
        })
    return out


def ticket_markdown() -> str:
    data = _load()
    roles, ms = data["roles"], data["milestones"]
    lines = [START, "", "| ID | Title | Owner | Milestone | Depends on | Contract |", "|---|---|---|---|---|---|"]
    for t in data["tickets"]:
        lines.append(f"| {t['id']} | {t['title']} | {roles[t['owner']]} | {t['milestone']} | "
                     f"{', '.join(t['depends_on']) or '-'} | `{t['contract']}` |")
    lines.append("")
    for t in data["tickets"]:
        lines.append(f"### {t['id']} - {t['title']}")
        lines.append(f"*Owner:* {roles[t['owner']]} · *Milestone:* {ms[t['milestone']]['title']} · "
                     f"*Depends on:* {', '.join(t['depends_on']) or 'none'} · *Contract:* `{t['contract']}`")
        lines.append("")
        lines += [f"- [ ] {a}" for a in t["acceptance"]]
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    (ROOT / "plan" / "issues.json").write_text(json.dumps(build_issues(), indent=2) + "\n")
    plan = ROOT / "docs" / "plan.md"
    text = plan.read_text()
    if START in text and END in text:
        pre, rest = text.split(START, 1)
        _, post = rest.split(END, 1)
        plan.write_text(pre + ticket_markdown() + post)
    print(f"wrote plan/issues.json ({len(build_issues())} issues) and updated docs/plan.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
