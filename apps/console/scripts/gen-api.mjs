import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { packageRoot } from "./package-root.mjs";

const consoleRoot = packageRoot();
const specPath = path.resolve(consoleRoot, "../../contracts/openapi.yaml");
const outFile = path.resolve(consoleRoot, "src/api/schema.d.ts");
const bin = path.resolve(consoleRoot, "node_modules/.bin/openapi-typescript");

const generateArgs = [
  specPath,
  "--empty-objects-unknown",
  "--default-non-nullable",
  "false",
];

const banner = `/**
 * Generated by \`npm run gen:api\` from contracts/openapi.yaml.
 * \`npm run check:api\` fails the build when this file drifts.
 * The JSON Schema \`$defs\` keyword is removed from the emitted type: openapi-typescript
 * 7.13 treats it as a required property, and it is not part of the instance document.
 * Those definitions are already hoisted onto \`components["schemas"]\`.
 */

`;

function generate(dest) {
  execFileSync(bin, [...generateArgs, "--output", dest], {
    cwd: consoleRoot,
    stdio: "inherit",
  });
  const source = stripSchemaDefs(readFileSync(dest, "utf8"));
  writeFileSync(dest, banner + normalize(source));
}

function normalize(text) {
  return text.replaceAll("\r\n", "\n").replace(/\n+$/u, "\n");
}

function stripSchemaDefs(source) {
  let next = stripProperty(source, "$defs");
  next = next.replace("export type $defs = Record<string, never>;\n", "");
  return next;
}

function stripProperty(source, name) {
  const marker = `\n            ${name}: {`;
  const start = source.indexOf(marker);
  if (start < 0) return source;
  const open = start + marker.length - 1;
  const close = findMatchingBrace(source, open);
  let end = close + 1;
  if (source[end] === ";") end += 1;
  return source.slice(0, start) + source.slice(end);
}

function findMatchingBrace(source, openIndex) {
  let depth = 0;
  for (let i = openIndex; i < source.length; i += 1) {
    const ch = source[i];
    if (ch === "/" && source[i + 1] === "/") {
      const newline = source.indexOf("\n", i);
      i = newline < 0 ? source.length : newline;
      continue;
    }
    if (ch === "/" && source[i + 1] === "*") {
      const closeComment = source.indexOf("*/", i + 2);
      if (closeComment < 0) throw new Error("unterminated comment in generated types");
      i = closeComment + 1;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      i = skipString(source, i);
      continue;
    }
    if (ch === "{") depth += 1;
    else if (ch === "}") {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  throw new Error("unbalanced brace while stripping $defs from generated types");
}

function skipString(source, start) {
  const quote = source[start];
  for (let i = start + 1; i < source.length; i += 1) {
    if (source[i] === "\\") {
      i += 1;
      continue;
    }
    if (source[i] === quote) return i;
  }
  throw new Error("unterminated string in generated types");
}

const check = process.argv.includes("--check");
if (check) {
  const dir = mkdtempSync(path.join(tmpdir(), "console-api-"));
  const dest = path.join(dir, "schema.d.ts");
  try {
    generate(dest);
    const next = readFileSync(dest, "utf8");
    const current = readFileSync(outFile, "utf8");
    if (next !== current) {
      console.error("Generated API types drifted from contracts/openapi.yaml.");
      console.error("Run `npm run gen:api` in apps/console and commit src/api/schema.d.ts.");
      try {
        execFileSync("git", ["diff", "--no-index", "--", outFile, dest], { stdio: "inherit" });
      } catch {
        // git diff --no-index exits 1 when the files differ.
      }
      process.exitCode = 1;
    } else {
      console.log("API types match contracts/openapi.yaml");
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
} else {
  generate(outFile);
  console.log(`wrote ${path.relative(consoleRoot, outFile)}`);
}
